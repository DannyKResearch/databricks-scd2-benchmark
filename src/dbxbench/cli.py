"""dbxbench command line.

    dbxbench doctor   --config C [--run-id R] [--no-write-probes]
    dbxbench init     --config C --run-id R [--dry-run] [--resume]
    dbxbench generate --config C --run-id R
    dbxbench run      --config C --run-id R [--cell K ...] [--kind performance|contention|fault] [--resume] [--dry-run]
    dbxbench verify   --config C --run-id R
    dbxbench analyze  --config C --run-id R [--no-charts]
    dbxbench cleanup  --config C --run-id R --yes [--dry-run] [--discard-failure-evidence]
    dbxbench smoke    --config C [--run-id R]          (doctor+init+generate+run+verify+analyze)

Authentication for Databricks uses the standard SDK chain (env vars / ~/.databrickscfg profile /
OAuth / job identity). The CLI never accepts or prints credentials.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import sys
from typing import Any

from .config import BenchConfig, load_config
from .logging_setup import configure_logging
from .naming import new_run_id, validate_run_id

log = logging.getLogger("dbxbench")


def _csv(v: str | None) -> list[str] | None:
    return [x.strip() for x in v.split(",") if x.strip()] if v else None


def _ints(v: str | None) -> list[int] | None:
    return [int(x) for x in v.split(",")] if v else None


def build_parser() -> argparse.ArgumentParser:
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--config", required=True, help="YAML config (see config/example.yaml)")
    common.add_argument("--run-id", default=None, help="unique run id (generated by init/smoke if omitted)")
    common.add_argument("--dry-run", action="store_true", help="print intended SQL/table names; change nothing")
    common.add_argument("--log-level", default="INFO")
    common.add_argument(
        "--git-sha", default=None, help="commit recorded in run_manifest.json (serverless jobs cannot set env vars)"
    )
    o = common.add_argument_group("overrides")
    o.add_argument("--tables", type=int)
    o.add_argument("--rows", type=int)
    o.add_argument("--publications", type=int)
    o.add_argument("--scopes", type=int)
    o.add_argument("--changed-fraction", type=float)
    o.add_argument("--writers", help="comma list, e.g. 1,2,5")
    o.add_argument("--formats", help="comma list: delta,iceberg")
    o.add_argument("--strategies", help="comma list: scd2_full,append_only_full,scd2_changed_only")
    o.add_argument("--contention", help="comma list: same_scope,disjoint_scopes,overlapping_tables")
    o.add_argument("--ordering", help="comma list: off,monotonic,sequenced")
    o.add_argument("--launcher", help="inline|local_process|databricks_jobs")
    o.add_argument("--catalog")
    o.add_argument("--results-root")
    o.add_argument("--repetitions", type=int)
    o.add_argument("--worker-job-id", type=int, help="job id of the deployed dbxbench_worker job")
    o.add_argument("--compute-mode", help="jobs_cluster|serverless|existing_cluster|local")
    o.add_argument("--schema-prefix", help="per-run schema = <prefix>_<run_id> (live tests use dbxbench_live)")
    o.add_argument("--schema-layout", help="single|per_cell")

    p = argparse.ArgumentParser(prog="dbxbench", description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)
    d = sub.add_parser("doctor", parents=[common], help="probe the environment; write capabilities.json")
    d.add_argument("--no-write-probes", action="store_true")
    i = sub.add_parser("init", parents=[common], help="plan cells, gate by capabilities, create run-owned tables")
    i.add_argument("--resume", action="store_true")
    sub.add_parser("generate", parents=[common], help="materialize immutable staging data")
    r = sub.add_parser("run", parents=[common], help="execute planned cells")
    r.add_argument("--cell", action="append", default=None)
    r.add_argument("--kind", action="append", default=None, choices=["performance", "contention", "fault"])
    r.add_argument("--resume", action="store_true", help="skip cells already COMPLETE/FAILED")
    sub.add_parser("verify", parents=[common], help="re-run all invariants + parity from persisted state")
    a = sub.add_parser("analyze", parents=[common], help="summaries, CSV exports, report.md and charts")
    a.add_argument("--no-charts", action="store_true")
    c = sub.add_parser("cleanup", parents=[common], help="drop run-owned objects (explicit, ownership-checked)")
    c.add_argument("--yes", action="store_true")
    c.add_argument(
        "--discard-failure-evidence",
        nargs="?",
        const="yes",
        default="no",
        choices=["yes", "no"],
        help="drop tables of FAILED cells too (results files are always kept)",
    )
    s = sub.add_parser("smoke", parents=[common], help="doctor+init+generate+run+verify+analyze")
    s.add_argument("--kind", action="append", default=None, choices=["performance", "contention", "fault"])
    return p


def _overrides(a: argparse.Namespace) -> dict[str, Any]:
    return {
        "tables": a.tables,
        "rows": a.rows,
        "publications": a.publications,
        "scopes": a.scopes,
        "changed_fraction": a.changed_fraction,
        "writers": _ints(a.writers),
        "formats": _csv(a.formats),
        "strategies": _csv(a.strategies),
        "contention": _csv(a.contention),
        "ordering": _csv(a.ordering),
        "launcher": a.launcher,
        "catalog": a.catalog,
        "results_root": a.results_root,
        "repetitions": a.repetitions,
        "worker_job_id": a.worker_job_id,
        "compute_mode": a.compute_mode,
        "schema_prefix": a.schema_prefix,
        "schema_layout": a.schema_layout,
    }


def _need_run_id(a: argparse.Namespace) -> str:
    if not a.run_id:
        raise SystemExit("--run-id is required for this command")
    return validate_run_id(a.run_id)


def _print(obj: Any) -> None:
    print(json.dumps(obj, indent=2, default=str))


def _dry_run_sql(rt: Any) -> None:
    from .engine import PublicationEngine  # noqa: F401 - imported for parity with runtime path
    from .runner import init
    from .scenarios import CellKind
    from .sqlgen import TxnContext, build_publication_sql

    plan = init(rt)
    print(
        "-- ===== DRY RUN: nothing is executed; run-owned namespace:",
        f"{rt.ns.catalog}.{rt.ns.schema}",
        f"(table prefix '{rt.ns.table_prefix}')" if rt.ns.table_prefix else "",
    )
    print(
        f"-- {len(plan.cells)} cells; estimated rows written ~{plan.estimated_rows:,}; "
        f"~{plan.estimated_bytes / 1e9:.3f} GB uncompressed"
    )
    print("\n-- ===== DDL (outside any transaction)")
    for s in rt.ddl:
        print(s + ";\n")
    shown: set[str] = set()
    for cell in plan.cells:
        k = f"{cell.kind.value}:{cell.strategy.value}:{cell.fmt.value}"
        if k in shown or not cell.writers or not cell.writers[0].publications:
            continue
        shown.add(k)
        pub = cell.writers[0].publications[0]
        ctx = TxnContext(
            rt.run_id,
            cell.cell_key,
            cell.strategy,
            cell.ordering,
            cell.writers[0].writer_id,
            f"{cell.writers[0].writer_id}-dryrun",
            1,
            rt.tables_for(cell),
            rt.staging_for(cell),
            cell.fault if cell.kind is CellKind.FAULT else None,
        )
        print(
            f"\n-- ===== publication transaction ({k}, cell {cell.cell_key}, {pub.publication_id}) "
            f"— submitted as ONE spark.sql() call"
        )
        print(build_publication_sql(ctx, pub, rt.dialect))


def dispatch(a: argparse.Namespace) -> int:
    from . import runner as R
    from .results import RunPaths

    cfg: BenchConfig = load_config(a.config, _overrides(a))
    cmd = a.command
    if cmd in ("init", "smoke") and not a.run_id:
        a.run_id = new_run_id()
        log.info("generated run_id %s", a.run_id)
    if cmd == "doctor":
        rid = validate_run_id(a.run_id) if a.run_id else new_run_id()
        rt = R.Runtime(cfg, rid, dry_run=a.dry_run)
        m = R.doctor(rt, write_probes=not a.no_write_probes)
        _print(m.to_json())
        print(
            f"capabilities written to {rt.paths.capabilities}" if not a.dry_run else "dry-run: no probes run",
            file=sys.stderr,
        )
        return 0
    rid = _need_run_id(a)
    rt = R.Runtime(cfg, rid, dry_run=a.dry_run)
    if cmd == "init":
        if a.dry_run:
            _dry_run_sql(rt)
            return 0
        plan = R.init(rt, resume=a.resume)
        _print(
            {
                "run_id": rid,
                "cells": len(plan.cells),
                "results": str(rt.paths.root),
                "estimated_rows": plan.estimated_rows,
                **_cost_warning(plan),
            }
        )
        return 0
    if a.dry_run and cmd in ("generate", "run", "verify", "cleanup", "smoke"):
        if cmd == "cleanup":
            raise SystemExit(
                "cleanup --dry-run needs the live catalog to check ownership; omit --dry-run to "
                "see the refusal checks, or use --dry-run with a live session via the job"
            )
        _dry_run_sql(rt)
        return 0
    if cmd == "generate":
        _print(R.generate(rt))
        return 0
    if cmd == "run":
        statuses = R.run(rt, only=a.cell, resume=a.resume, kinds=a.kind)
        _print(statuses)
        return 1 if any(v == "FAILED" for v in statuses.values()) or _any_fail_verdict(rt) else 0
    if cmd == "verify":
        out = R.verify(rt)
        _print(out)
        bad = [k for k, v in out["cells"].items() if str(v["verdict"]).startswith("FAIL")] + [
            p["name"] for p in out["parity"] if p["status"] != "PASS"
        ]
        return 1 if bad else 0
    if cmd == "analyze":
        return _analyze(rt, charts=cfg.reporting.charts and not a.no_charts)
    if cmd == "cleanup":
        from .cleanup import CleanupRefused, execute_cleanup, plan_cleanup

        try:
            cp = plan_cleanup(
                cfg, rid, rt.executor, yes=a.yes, discard_failure_evidence=a.discard_failure_evidence == "yes"
            )
        except CleanupRefused as exc:
            print(f"REFUSED: {exc}", file=sys.stderr)
            return 2
        for w in cp.warnings:
            print(w, file=sys.stderr)
        _print({"executed": execute_cleanup(cp, rt.executor, dry_run=False)})
        return 0
    if cmd == "smoke":
        R.doctor(rt)
        R.init(rt)
        R.generate(rt)
        statuses = R.run(rt, kinds=a.kind)
        R.verify(rt)
        rc = _analyze(rt, charts=cfg.reporting.charts)
        _print(
            {"run_id": rid, "statuses": statuses, "results": str(RunPaths.for_run(cfg.project.results_root, rid).root)}
        )
        return rc
    raise SystemExit(f"unknown command {cmd}")


def _cost_warning(plan: Any) -> dict[str, Any]:
    from .config import Launcher

    runs = sum(c.writer_count for c in plan.cells if c.launcher is Launcher.DATABRICKS_JOBS)
    peak = max((c.writer_count for c in plan.cells if c.launcher is Launcher.DATABRICKS_JOBS), default=0)
    out: dict[str, Any] = {"independent_job_runs_to_launch": runs, "peak_concurrent_job_runs": peak}
    if runs:
        print(
            f"COST WARNING: contention cells will launch {runs} separate job runs (up to {peak} clusters at "
            "once). Check cluster policy/quotas before `run --kind contention`.",
            file=sys.stderr,
        )
    return out


def _any_fail_verdict(rt: Any) -> bool:
    from .results import read_json

    cells = rt.paths.root / "cells"
    for st in cells.glob("*/status.json") if cells.exists() else []:
        if str(read_json(st).get("verdict") or "").startswith("FAIL"):
            return True
    return False


def _analyze(rt: Any, charts: bool) -> int:
    from .analysis import analyse_run
    from .report import build_report
    from .runner import finalize_manifest

    if not rt.paths.manifest.exists():
        finalize_manifest(rt)
    summary = analyse_run(rt.paths)
    report = build_report(rt.paths, charts=charts)
    corr = summary["correctness"]
    _print({"report": str(report), "correctness": corr})
    unexpected_skip = rt.cfg.benchmark.fail_on_unexpected_skip and corr["cells_skipped"] > 0
    return 1 if corr["verdict"] == "FAIL" or unexpected_skip else 0


def main(argv: list[str] | None = None) -> int:
    p = build_parser()
    a = p.parse_args(argv)
    configure_logging(a.log_level)
    if a.git_sha and a.git_sha != "unknown":
        os.environ["DBXBENCH_GIT_SHA"] = a.git_sha
    try:
        return dispatch(a)
    except Exception as exc:
        log.error("%s: %s", type(exc).__name__, exc)
        if a.log_level == "DEBUG":
            raise
        return 1


def task_main() -> int:
    """Databricks python_wheel_task entry point (same commands, parameters from the job)."""
    return main(sys.argv[1:])


if __name__ == "__main__":
    sys.exit(main())
